CREATE TABLE app_user (
 id VARCHAR(36) PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE,
 display_name VARCHAR(100) NOT NULL, password_hash VARCHAR(100) NOT NULL,
 created_at BIGINT NOT NULL
);
CREATE TABLE auth_session (
 token_hash VARCHAR(64) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id), expires_at BIGINT NOT NULL
);
CREATE TABLE file_entry (
 id VARCHAR(36) PRIMARY KEY, owner_id VARCHAR(36) NOT NULL REFERENCES app_user(id),
 parent_id VARCHAR(36) REFERENCES file_entry(id), parent_key VARCHAR(36) NOT NULL,
 name VARCHAR(255) NOT NULL, name_key VARCHAR(255), kind VARCHAR(10) NOT NULL CHECK(kind IN ('FILE','FOLDER')),
 current_version VARCHAR(36), trashed_at BIGINT, conflict_of VARCHAR(36) REFERENCES file_entry(id),
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,
 UNIQUE(owner_id, parent_key, name_key)
);
CREATE TABLE content_object (
 id VARCHAR(36) PRIMARY KEY, object_key VARCHAR(300) NOT NULL UNIQUE,
 size BIGINT NOT NULL CHECK(size >= 0), sha256 VARCHAR(64) NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE file_version (
 id VARCHAR(36) PRIMARY KEY, file_id VARCHAR(36) NOT NULL REFERENCES file_entry(id),
 content_id VARCHAR(36) NOT NULL REFERENCES content_object(id), version_no INTEGER NOT NULL,
 source VARCHAR(100) NOT NULL, restored_from VARCHAR(36) REFERENCES file_version(id),
 created_at BIGINT NOT NULL, UNIQUE(file_id, version_no)
);
ALTER TABLE file_entry ADD CONSTRAINT current_version_fk FOREIGN KEY(current_version) REFERENCES file_version(id);
CREATE TABLE upload_session (
 id VARCHAR(36) PRIMARY KEY, owner_id VARCHAR(36) NOT NULL REFERENCES app_user(id),
 request_key VARCHAR(100) NOT NULL, request_hash VARCHAR(64) NOT NULL,
 target_id VARCHAR(36) REFERENCES file_entry(id), parent_id VARCHAR(36) REFERENCES file_entry(id),
 name VARCHAR(255) NOT NULL, base_version VARCHAR(36), size BIGINT NOT NULL, sha256 VARCHAR(64) NOT NULL,
 part_size INTEGER NOT NULL, part_count INTEGER NOT NULL, source VARCHAR(100) NOT NULL,
 state VARCHAR(20) NOT NULL CHECK(state IN ('OPEN','PUBLISHED','CONFLICT','CANCELLED','EXPIRED')),
 result_file VARCHAR(36) REFERENCES file_entry(id), result_version VARCHAR(36) REFERENCES file_version(id),
 expires_at BIGINT NOT NULL, created_at BIGINT NOT NULL, UNIQUE(owner_id, request_key)
);
CREATE TABLE upload_part (
 session_id VARCHAR(36) NOT NULL REFERENCES upload_session(id), part_no INTEGER NOT NULL,
 size INTEGER NOT NULL, sha256 VARCHAR(64) NOT NULL, object_key VARCHAR(300) NOT NULL,
 PRIMARY KEY(session_id,part_no)
);
CREATE TABLE share_link (
 id VARCHAR(36) PRIMARY KEY, owner_id VARCHAR(36) NOT NULL REFERENCES app_user(id),
 version_id VARCHAR(36) NOT NULL REFERENCES file_version(id), token_hash VARCHAR(64) NOT NULL UNIQUE,
 expires_at BIGINT NOT NULL, revoked_at BIGINT, created_at BIGINT NOT NULL
);
CREATE TABLE activity_event (
 id VARCHAR(36) PRIMARY KEY, owner_id VARCHAR(36) NOT NULL REFERENCES app_user(id),
 action VARCHAR(50) NOT NULL, file_id VARCHAR(36), version_id VARCHAR(36),
 name VARCHAR(255) NOT NULL, detail VARCHAR(500) NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE change_event (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id VARCHAR(36) NOT NULL REFERENCES app_user(id),
 file_id VARCHAR(36) NOT NULL, version_id VARCHAR(36), action VARCHAR(50) NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE operation_result (
 owner_id VARCHAR(36) NOT NULL REFERENCES app_user(id), request_key VARCHAR(100) NOT NULL,
 request_hash VARCHAR(64) NOT NULL, version_id VARCHAR(36) NOT NULL REFERENCES file_version(id),
 PRIMARY KEY(owner_id,request_key)
);
CREATE INDEX file_owner_parent ON file_entry(owner_id,parent_id);
CREATE INDEX activity_owner_time ON activity_event(owner_id,created_at);
CREATE INDEX change_owner_seq ON change_event(owner_id,seq);
CREATE INDEX uploads_expiry ON upload_session(state,expires_at);
